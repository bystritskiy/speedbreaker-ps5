#!/usr/bin/env python3
"""SpeedBreaker PS5: the Vulkan loader's exports, for a statically linked RADV.

    python3 -I port/ps5/tools/gen-vulkan-shim.py <vulkan_core.h> <out.c>

The console has no Vulkan loader: RADV is linked into the app and exports
only vk_icdGetInstanceProcAddr. The runtime (video/presenter.cpp,
gpu/renderer.cpp) and Dear ImGui's Vulkan backend call vkXxx directly, as
against a loader, so this writes one definition of every command the header
declares. Each resolves its RADV entry point once, through
vk_icdGetInstanceProcAddr with the instance vkCreateInstance made (global
commands with none); Mesa returns its dispatching trampolines for physical
device and device commands there, so one pointer serves every handle.
A command RADV doesn't have aborts with its name when called.
"""
import re
import sys

PROTO = re.compile(r'VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\((.*?)\);', re.S)
GLOBAL = {
    'vkCreateInstance', 'vkEnumerateInstanceExtensionProperties',
    'vkEnumerateInstanceLayerProperties', 'vkEnumerateInstanceVersion',
    'vkGetInstanceProcAddr',
}


def param_name(param):
    param = re.sub(r'\[[^\]]*\]', '', param).strip()
    return re.findall(r'\w+', param)[-1]


def main():
    header, out = sys.argv[1], sys.argv[2]
    text = open(header).read()
    # Only the prototypes (#ifndef VK_NO_PROTOTYPES blocks), not the typedefs.
    commands = []
    seen = set()
    for ret, name, params in PROTO.findall(text):
        if name in seen:
            continue
        seen.add(name)
        params = ' '.join(params.split())
        names = [] if params in ('', 'void') else [param_name(p) for p in params.split(',')]
        commands.append((ret.strip(), name, params, names))

    lines = [
        '// Generated by port/ps5/tools/gen-vulkan-shim.py. Do not edit.',
        '#include <stdio.h>',
        '#include <stdlib.h>',
        '#include <vulkan/vulkan_core.h>',
        '',
        'extern PFN_vkVoidFunction VKAPI_CALL vk_icdGetInstanceProcAddr(VkInstance, const char*);',
        'static VkInstance sb_vk_instance;',
        '',
        'static PFN_vkVoidFunction sb_vk_resolve(VkInstance instance, const char* name)',
        '{',
        '    PFN_vkVoidFunction fn = vk_icdGetInstanceProcAddr(instance, name);',
        '    if (!fn)',
        '    {',
        '        fprintf(stderr, "[vulkan] RADV has no %s\\n", name);',
        '        abort();',
        '    }',
        '    return fn;',
        '}',
        '',
    ]
    for ret, name, params, names in commands:
        args = ', '.join(names)
        if name == 'vkGetInstanceProcAddr':
            lines += [
                f'VKAPI_ATTR {ret} VKAPI_CALL {name}({params})',
                '{',
                '    return vk_icdGetInstanceProcAddr(instance, pName);',
                '}', '']
            continue
        instance = 'VK_NULL_HANDLE' if name in GLOBAL else 'sb_vk_instance'
        call = f'fn({args})'
        body = [
            f'    static PFN_{name} fn;',
            '    if (!fn)',
            f'        fn = (PFN_{name})sb_vk_resolve({instance}, "{name}");',
        ]
        if name == 'vkCreateInstance':
            body += [
                f'    VkResult result = {call};',
                '    if (result == VK_SUCCESS)',
                '        sb_vk_instance = *pInstance;',
                '    return result;',
            ]
        elif ret == 'void':
            body.append(f'    {call};')
        else:
            body.append(f'    return {call};')
        lines += [f'VKAPI_ATTR {ret} VKAPI_CALL {name}({params})', '{', *body, '}', '']
    open(out, 'w').write('\n'.join(lines))
    print(f'{len(commands)} Vulkan commands -> {out}')


if __name__ == '__main__':
    main()
